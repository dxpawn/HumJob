"use strict";

// Manual transcribe mode - the client-side MusicXML builder (Phase 1).
//
// notesToMusicXML(seq, opts) turns the editor's monophonic sequence model into
// MusicXML that verovio-WASM can engrave in the browser, WITHOUT a server round
// trip. It must produce notation that matches, note for note, what the server's
// music21 path (export.build_stream) produces for the same melody: same spelled
// pitch, quarter-length duration, tie flags, measure numbers, clef, and key/time
// signatures. Layout, ids, and beams are intentionally NOT matched.
//
// Pure and headless: no DOM, no network. Exposed on window.MT (like realtime.js's
// window.RT) and as a node module so tests/manual/builder.test.mjs can drive it and
// assert against the golden generated by tests/gen_manual_golden.py.
//
// Sequence model: seq is an ordered array of events, each a note
// { midi, durTicks } or a rest { rest:true, durTicks }. durTicks is measured in
// 1/divisions of a quarter note (a grid tick); onsets are implied by the running
// sum (reflow). No em/en dashes or emojis per CLAUDE.md.

const MT = (() => {
  // Spelling tables mirror export.py (_SHARP / _FLAT). '-' = flat, '#' = sharp.
  const SHARP = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"];
  const FLAT = ["C", "D-", "D", "E-", "E", "F", "G-", "G", "A-", "A", "B-", "B"];

  // useFlats mirrors export._parse_key: music21.Key(tonic, mode).sharps < 0, where
  // the tonic is spelled with the SHARP names key.py emits. Baked from music21 so
  // the browser needs no music21: major keys take flats only at F; minor keys at
  // C, D, F, G. (Verified against music21 for all 24 keys, 2026-08-04.)
  const MAJOR_FLAT_PCS = new Set([5]);            // F major
  const MINOR_FLAT_PCS = new Set([0, 2, 5, 7]);   // C, D, F, G minor

  // Key-signature fifths (sharps count; negative = flats) per tonic pitch class and
  // mode, matching music21.Key(SHARP[pc], mode).sharps. Theoretical spellings (e.g.
  // D# major = 9) are kept for parity with the server even though a real MusicXML
  // reader clamps them; realistic hums land in the common keys.
  const MAJOR_FIFTHS = [0, 7, 2, 9, 4, -1, 6, 1, 8, 3, 10, 5];
  const MINOR_FIFTHS = [-3, 4, -1, 6, 1, -4, 3, -2, 5, 0, 7, 2];

  const STEP_DIATONIC = { C: 1, D: 2, E: 3, F: 4, G: 5, A: 6, B: 7 };
  const KIND = { maj: "major", min: "minor", dim: "diminished" };

  // ---- key + pitch spelling -------------------------------------------------

  function parseKey(keyStr) {
    // Returns { pc, mode, useFlats, fifths }. Mirrors _parse_key's except-branch:
    // an empty/unparseable key means no key signature and flat spelling.
    if (!keyStr) return { pc: null, mode: null, useFlats: true, fifths: 0 };
    const parts = String(keyStr).trim().split(/\s+/);
    const tonic = parts[0];
    const mode = (parts[1] || "").toLowerCase();
    const pc = SHARP.indexOf(tonic);
    if (pc < 0 || (mode !== "major" && mode !== "minor")) {
      return { pc: null, mode: null, useFlats: true, fifths: 0 };
    }
    const useFlats = mode === "major" ? MAJOR_FLAT_PCS.has(pc) : MINOR_FLAT_PCS.has(pc);
    const fifths = mode === "major" ? MAJOR_FIFTHS[pc] : MINOR_FIFTHS[pc];
    return { pc, mode, useFlats, fifths };
  }

  function spell(midi, useFlats) {
    // Mirrors export._spell: pc name from the sharp/flat table, octave = midi//12-1.
    const pc = ((midi % 12) + 12) % 12;
    const octave = Math.floor(midi / 12) - 1;
    const name = (useFlats ? FLAT : SHARP)[pc];
    const step = name[0];
    const alter = name.length > 1 ? (name[1] === "#" ? 1 : -1) : 0;
    return { step, alter, octave };
  }

  function bestClefSign(noteEvents) {
    // Mirrors music21.clef.bestClef: average diatonicNoteNum > 28 (middle C) is
    // treble, else bass. Extreme 8va/8vb clefs are not modeled (out of vocal range).
    if (!noteEvents.length) return "G";
    let sum = 0;
    for (const n of noteEvents) sum += n.octave * 7 + STEP_DIATONIC[n.step];
    return sum / noteEvents.length > 28 ? "G" : "F";
  }

  // ---- duration decomposition ----------------------------------------------

  function notatableSet(D) {
    // Notatable note values in divisions, largest first, for `D` divisions per
    // quarter. Includes single and double dots when they land on an integer count.
    const bases = [
      [4 * D, "whole"], [2 * D, "half"], [D, "quarter"],
      [D / 2, "eighth"], [D / 4, "16th"], [D / 8, "32nd"],
    ];
    const byDivs = new Map();
    for (const [b, type] of bases) {
      if (!Number.isInteger(b) || b < 1) continue;
      for (const [divs, dots] of [[b, 0], [b * 3 / 2, 1], [b * 7 / 4, 2]]) {
        if (!Number.isInteger(divs)) continue;
        const cur = byDivs.get(divs);
        if (!cur || dots < cur.dots) byDivs.set(divs, { divs, type, dots, base: b });
      }
    }
    return [...byDivs.values()].sort((a, b) => b.divs - a.divs);
  }

  function decompose(off, dur, D) {
    // Split a within-measure span [off, off+dur) into notatable components. If the
    // whole span is a single notatable value aligned to its base, keep it as one
    // symbol (so a dotted half stays a dotted half, matching music21). Otherwise
    // take the largest aligned value that fits, greedily, tying the pieces.
    const set = notatableSet(D);
    const single = set.find((it) => it.divs === dur && off % it.base === 0);
    if (single) return [single];
    const comps = [];
    let o = off, rem = dur, guard = 0;
    while (rem > 0 && guard++ < 256) {
      const pick = set.find((it) => it.divs <= rem && o % it.base === 0) || set[set.length - 1];
      comps.push(pick);
      o += pick.divs;
      rem -= pick.divs;
    }
    return comps;
  }

  // ---- XML emission ---------------------------------------------------------

  function harmonyXML(ch) {
    const rn = String(ch.root_name || "");
    const step = rn[0] || "C";
    const alter = rn.indexOf("-") >= 0 ? -1 : rn.indexOf("#") >= 0 ? 1 : 0;
    const alterXML = alter ? `<root-alter>${alter}</root-alter>` : "";
    const kind = KIND[ch.quality] || "major";
    return `      <harmony>\n` +
      `        <root><root-step>${step}</root-step>${alterXML}</root>\n` +
      `        <kind>${kind}</kind>\n` +
      `      </harmony>\n`;
  }

  function noteXML(el) {
    const dots = "<dot/>".repeat(el.dots);
    if (el.kind === "rest") {
      return `      <note><rest/><duration>${el.divs}</duration>` +
        `<type>${el.type}</type>${dots}</note>\n`;
    }
    const tieSound =
      el.tie === "start" ? '<tie type="start"/>'
      : el.tie === "stop" ? '<tie type="stop"/>'
      : el.tie === "continue" ? '<tie type="stop"/><tie type="start"/>' : "";
    const tied =
      el.tie === "start" ? '<tied type="start"/>'
      : el.tie === "stop" ? '<tied type="stop"/>'
      : el.tie === "continue" ? '<tied type="stop"/><tied type="start"/>' : "";
    const alterXML = el.alter ? `<alter>${el.alter}</alter>` : "";
    const pitch = `<pitch><step>${el.step}</step>${alterXML}<octave>${el.octave}</octave></pitch>`;
    const notations = tied ? `<notations>${tied}</notations>` : "";
    return `      <note>${pitch}<duration>${el.divs}</duration>${tieSound}` +
      `<type>${el.type}</type>${dots}${notations}</note>\n`;
  }

  // ---- the builder ----------------------------------------------------------

  function notesToMusicXML(seq, opts) {
    opts = opts || {};
    const D = opts.divisions || 4;
    const timeSig = opts.timeSig || [4, 4];
    const beats = timeSig[0], unit = timeSig[1];
    const key = parseKey(opts.key);
    const chords = opts.chords || [];
    const barDivs = Math.round(beats * (4 / unit) * D); // divisions per measure

    const spelled = seq.map((ev) => (ev.rest ? null : spell(ev.midi, key.useFlats)));
    const clefSign = bestClefSign(spelled.filter(Boolean));

    const measures = new Map(); // 1-based measure number -> array of elements
    const push = (mn, el) => {
      if (!measures.has(mn)) measures.set(mn, []);
      measures.get(mn).push(el);
    };

    let onset = 0; // running tick position, in divisions
    seq.forEach((ev, i) => {
      const total = Math.max(0, Math.round(ev.durTicks));
      if (total === 0) return;
      const isRest = !!ev.rest;
      const sp = spelled[i];

      // Break the event at each barline it crosses (notes tie across the splits).
      const pieces = [];
      let remaining = total, pos = onset;
      while (remaining > 0) {
        const mn = Math.floor(pos / barDivs) + 1;
        const off = pos - (mn - 1) * barDivs;
        const take = Math.min(remaining, barDivs - off);
        pieces.push({ mn, off, dur: take });
        pos += take;
        remaining -= take;
      }

      // Decompose each piece into notatable components; flatten with tie flags.
      const comps = [];
      for (const p of pieces) {
        for (const c of decompose(p.off, p.dur, D)) comps.push({ mn: p.mn, c });
      }
      comps.forEach((item, idx) => {
        let tie = null;
        if (!isRest && comps.length > 1) {
          tie = idx === 0 ? "start" : idx === comps.length - 1 ? "stop" : "continue";
        }
        push(item.mn, {
          kind: isRest ? "rest" : "note",
          divs: item.c.divs, type: item.c.type, dots: item.c.dots,
          step: sp ? sp.step : null, alter: sp ? sp.alter : 0,
          octave: sp ? sp.octave : null, tie, seqIndex: i,
        });
      });
      onset += total;
    });

    // A short final measure is left incomplete, matching music21's makeNotation
    // (it does not pad the last bar with rests). An empty score gets one bar rest.
    if (measures.size === 0) {
      push(1, {
        kind: "rest", divs: barDivs, type: "whole", dots: 0,
        step: null, alter: 0, octave: null, tie: null, seqIndex: -1,
      });
    }

    const chordByMeasure = new Map();
    for (const ch of chords) {
      const mn = (ch.measure | 0) + 1;
      if (!chordByMeasure.has(mn)) chordByMeasure.set(mn, ch);
    }

    const measureNos = [...measures.keys()].sort((a, b) => a - b);
    const noteheadMap = [];
    let body = "";
    for (const mn of measureNos) {
      body += `    <measure number="${mn}">\n`;
      if (mn === measureNos[0]) {
        body += `      <attributes>\n`;
        body += `        <divisions>${D}</divisions>\n`;
        if (key.pc !== null) {
          body += `        <key><fifths>${key.fifths}</fifths></key>\n`;
        }
        body += `        <time><beats>${beats}</beats><beat-type>${unit}</beat-type></time>\n`;
        body += `        <clef><sign>${clefSign}</sign><line>${clefSign === "F" ? 4 : 2}</line></clef>\n`;
        body += `      </attributes>\n`;
      }
      const ch = chordByMeasure.get(mn);
      if (ch) body += harmonyXML(ch);
      for (const el of measures.get(mn)) {
        if (el.kind === "note") noteheadMap.push(el.seqIndex);
        body += noteXML(el);
      }
      body += `    </measure>\n`;
    }

    const xml =
      `<?xml version="1.0" encoding="UTF-8"?>\n` +
      `<score-partwise version="3.1">\n` +
      `  <part-list><score-part id="P1"><part-name>Voice</part-name></score-part></part-list>\n` +
      `  <part id="P1">\n${body}  </part>\n` +
      `</score-partwise>\n`;
    return { xml, noteheadMap };
  }

  // ---- seq model from the auto transcription --------------------------------

  function seqFromNotes(notes, subdiv) {
    // Build the reflow sequence model from lastResult.notes. Onsets are implied by
    // the running sum; a gap between the previous note's end and this note's start
    // becomes an explicit rest. Overlaps (should not happen in a monophonic line)
    // are collapsed to a gapless onset.
    const D = subdiv || 4;
    const seq = [];
    let cursor = 0; // running position, in ticks
    for (const n of notes || []) {
      if (n.start_ql == null || n.dur_ql == null) continue;
      const startTicks = Math.round(n.start_ql * D);
      const durTicks = Math.max(1, Math.round(n.dur_ql * D));
      if (startTicks > cursor) {
        seq.push({ rest: true, durTicks: startTicks - cursor });
        cursor = startTicks;
      }
      seq.push({ midi: n.midi, durTicks, cents: n.cents });
      cursor = cursor + durTicks;
    }
    return seq;
  }

  const countNotes = (seq) => (seq || []).reduce((c, ev) => c + (ev.rest ? 0 : 1), 0);

  // ---- verovio-WASM lazy loader + client render (browser only) --------------

  const VEROVIO_SRC = "/vendor/verovio/verovio-toolkit-wasm.js";
  let vrvPromise = null;
  let toolkit = null;

  function loadVerovio() {
    // Inject the vendored verovio-WASM once and resolve with a ready toolkit. The
    // UMD build assigns window.verovio synchronously on load, then initializes the
    // Emscripten runtime asynchronously (calledRun flips true, onRuntimeInitialized
    // fires). Both are handled so there is no init race.
    if (toolkit) return Promise.resolve(toolkit);
    if (vrvPromise) return vrvPromise;
    vrvPromise = new Promise((resolve, reject) => {
      const build = () => {
        try {
          toolkit = new window.verovio.toolkit();
          resolve(toolkit);
        } catch (e) {
          reject(e);
        }
      };
      const whenReady = () => {
        const mod = window.verovio && window.verovio.module;
        if (!mod) return reject(new Error("verovio global missing after load"));
        if (mod.calledRun) build();
        else mod.onRuntimeInitialized = build;
      };
      if (window.verovio) return whenReady();
      let s = document.querySelector(`script[src="${VEROVIO_SRC}"]`);
      if (!s) {
        s = document.createElement("script");
        s.src = VEROVIO_SRC;
        s.async = true;
        document.head.appendChild(s);
      }
      s.addEventListener("load", whenReady);
      s.addEventListener("error", () => reject(new Error("verovio-WASM failed to load")));
    });
    return vrvPromise;
  }

  function engrave(tk, seq, opts) {
    // Synchronous seq -> engraved SVG using an already-loaded toolkit. Editing calls
    // this directly for an instant redraw (the toolkit is cached after the first
    // Manual entry). Options mirror export.sheet_svg_string for Auto/Manual parity.
    const built = notesToMusicXML(seq, opts);
    tk.setOptions({
      pageWidth: 2100,
      pageHeight: 900 + 300 * Math.max(0, Math.floor(countNotes(seq) / 24)),
      scale: 45,
      adjustPageHeight: true,
      header: "none",
      footer: "none",
    });
    if (tk.loadData(built.xml) === false) {
      throw new Error("verovio failed to load the edited MusicXML");
    }
    let svg = tk.renderToSVG(1);
    // Match the server: draw a white paper background so the sheet reads on any theme.
    svg = svg.replace(/(<svg\b[^>]*>)/, '$1<rect width="100%" height="100%" fill="#fff"/>');
    return { svg, xml: built.xml, noteheadMap: built.noteheadMap };
  }

  function renderSeq(seq, opts) {
    return loadVerovio().then((tk) => engrave(tk, seq, opts));
  }

  // ---- pure edit operations over the reflow seq -----------------------------
  //
  // Each returns a NEW seq plus the seq index that should stay selected, so they
  // are deterministic and headless-testable (tests/manual/builder.test.cjs). The
  // controller applies one, then re-engraves. `i` is a seq index; ops on a rest or
  // out of range are no-ops. Reflow (onsets = running sum of durTicks) means a
  // duration or structural change shifts the following notes automatically.

  const clampMidi = (m) => Math.max(12, Math.min(108, Math.round(m)));

  function snapSel(seq, sel) {
    // Nearest note (non-rest) seq index to `sel`; -1 if the seq has no notes.
    if (sel >= 0 && sel < seq.length && !seq[sel].rest) return sel;
    let best = -1, bestD = Infinity;
    for (let j = 0; j < seq.length; j++) {
      if (seq[j].rest) continue;
      const d = Math.abs(j - sel);
      if (d < bestD) { bestD = d; best = j; }
    }
    return best;
  }

  const cloneSeq = (seq) => seq.map((e) => ({ ...e }));

  const EDITS = {
    pitch(seq, i, deltaSemis) {
      const s = cloneSeq(seq);
      if (i >= 0 && i < s.length && !s[i].rest) {
        s[i].midi = clampMidi(s[i].midi + deltaSemis);
        s[i].cents = null; // the detected-cents no longer describes the chosen pitch
      }
      return { seq: s, sel: i };
    },
    duration(seq, i, deltaTicks) {
      const s = cloneSeq(seq);
      if (i >= 0 && i < s.length) {
        s[i].durTicks = Math.max(1, Math.round(s[i].durTicks) + deltaTicks);
      }
      return { seq: s, sel: i };
    },
    mergeNext(seq, i) {
      // Fuse note i with the following event into one note (i's pitch, summed
      // duration). The sliver fix: two fragments of a held note become one.
      if (i < 0 || i >= seq.length - 1) return { seq: cloneSeq(seq), sel: snapSel(seq, i) };
      const s = cloneSeq(seq);
      s[i].durTicks = Math.round(s[i].durTicks) + Math.round(s[i + 1].durTicks);
      s.splice(i + 1, 1);
      return { seq: s, sel: snapSel(s, i) };
    },
    split(seq, i) {
      const s = cloneSeq(seq);
      const d = i >= 0 && i < s.length ? Math.round(s[i].durTicks) : 0;
      if (d < 2) return { seq: s, sel: snapSel(s, i) }; // too short to split
      const a = Math.floor(d / 2);
      s.splice(i, 1, { ...s[i], durTicks: a }, { ...s[i], durTicks: d - a });
      return { seq: s, sel: i };
    },
    deleteToRest(seq, i) {
      const s = cloneSeq(seq);
      if (i >= 0 && i < s.length && !s[i].rest) {
        s[i] = { rest: true, durTicks: Math.round(s[i].durTicks) };
      }
      return { seq: s, sel: snapSel(s, i) };
    },
    insertAfter(seq, i, divisions) {
      const s = cloneSeq(seq);
      const at = i >= 0 ? i + 1 : s.length;
      const midi = i >= 0 && !s[i].rest ? s[i].midi : 69; // default A4
      s.splice(at, 0, { midi, durTicks: divisions || 4, cents: null });
      return { seq: s, sel: at };
    },
  };

  // ---- display helpers ------------------------------------------------------

  const DISPLAY_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"];
  function noteName(midi) {
    const pc = ((midi % 12) + 12) % 12;
    return DISPLAY_NAMES[pc] + (Math.floor(midi / 12) - 1);
  }
  const hzToMidi = (hz) => 69 + 12 * Math.log2(hz / 440);

  // ---- Manual-mode controller: selection + editing + reference strip (browser)
  //
  // Stateful; app.js creates one instance and calls enter()/exit() from the
  // Auto/Manual toggle. Select a note (click / Left-Right / the strip), edit it
  // (buttons + keys), and the staff re-engraves instantly via the cached toolkit.
  // Edits mutate a reflow `seq` through the pure EDITS ops; undo/redo snapshot it.
  // refs: { sheet, pane, strip, readout, tools, status, onEdit, onRescore }.

  function createManual(refs) {
    const sheetEl = refs.sheet;
    const paneEl = refs.pane;       // wraps strip + tools + readout; shown only in Manual
    const stripEl = refs.strip;     // <canvas>
    const readoutEl = refs.readout;

    let seq = [];
    let opts = null;                // { key, timeSig, divisions, tempo, chords }
    let frames = [];
    let noteheadMap = [];
    let layout = [];                // ordered note events (no rests): {seqIndex,midi,cents,startSec,endSec}
    let selSeq = -1;                // seq index of the selected note; -1 = none
    let active = false;
    let maxT = 1;                   // strip time span in seconds (set by drawStrip)
    let tk = null;                  // cached verovio toolkit (for instant re-engrave)
    let originalResult = null;      // identity of the take we seeded from
    let original = null;            // { notes, key, chords, candidates } for Revert
    let undoStack = [];
    let redoStack = [];

    const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
    const cssVar = (n) =>
      getComputedStyle(document.documentElement).getPropertyValue(n).trim() || "#888";
    const setStatus = (m) => { if (refs.status) refs.status.textContent = m || ""; };

    function buildLayout() {
      const D = opts.divisions || 4;
      const secPerTick = 60 / (opts.tempo || 120) / D;
      layout = [];
      let onset = 0;
      seq.forEach((ev, i) => {
        const dur = Math.max(1, Math.round(ev.durTicks));
        if (!ev.rest) {
          layout.push({
            seqIndex: i,
            midi: ev.midi,
            cents: ev.cents == null ? null : ev.cents,
            startSec: onset * secPerTick,
            endSec: (onset + dur) * secPerTick,
          });
        }
        onset += dur;
      });
    }

    const layoutPos = () => layout.findIndex((n) => n.seqIndex === selSeq);
    const noteGroups = () => sheetEl.querySelectorAll("g.note");

    function seqToNotes() {
      // Convert the reflow seq back to the transcribe `notes` shape, for playback
      // (app.js reads lastResult.notes) and the edited export payload.
      const D = opts.divisions || 4;
      const out = [];
      let onset = 0;
      for (const ev of seq) {
        const dur = Math.max(1, Math.round(ev.durTicks));
        if (!ev.rest) {
          out.push({
            name: noteName(ev.midi), midi: ev.midi,
            start_ql: onset / D, dur_ql: dur / D,
            cents: ev.cents == null ? 0 : Math.round(ev.cents),
          });
        }
        onset += dur;
      }
      return out;
    }

    function wireNoteClicks() {
      noteGroups().forEach((g, domIdx) => {
        g.addEventListener("click", (e) => {
          e.stopPropagation();
          selectNote(noteheadMap[domIdx]);
        });
      });
    }

    function applyHighlight() {
      noteGroups().forEach((g, domIdx) => {
        g.classList.toggle("mt-selected", noteheadMap[domIdx] === selSeq);
      });
    }

    function updateReadout() {
      if (!readoutEl) return;
      const pos = layoutPos();
      if (pos < 0 || !layout.length) {
        readoutEl.textContent = "Click a note (or use the arrow keys) to select it, then edit it below.";
        return;
      }
      const n = layout[pos];
      let txt = `Note ${pos + 1} of ${layout.length}: ${noteName(n.midi)}`;
      if (n.cents != null && Math.abs(n.cents) >= 1) {
        txt += ` (you hummed it ${n.cents > 0 ? "+" : ""}${Math.round(n.cents)} cents off)`;
      }
      readoutEl.textContent = txt;
    }

    function selectNote(si) {
      selSeq = si;
      applyHighlight();
      updateReadout();
      drawStrip();
    }

    function nav(dir) {
      if (!layout.length) return;
      let pos = layoutPos();
      pos = pos < 0 ? 0 : clamp(pos + dir, 0, layout.length - 1);
      selectNote(layout[pos].seqIndex);
    }

    function drawStrip() {
      if (!stripEl) return;
      const ctx = stripEl.getContext("2d");
      const W = stripEl.width, H = stripEl.height;
      ctx.clearRect(0, 0, W, H);

      const noteEnd = layout.length ? layout[layout.length - 1].endSec : 0;
      const frameEnd = frames.length ? frames[frames.length - 1].t : 0;
      maxT = Math.max(0.5, noteEnd, frameEnd);

      // Pitch range spans both the chosen notes and the hummed contour, padded.
      let lo = Infinity, hi = -Infinity;
      for (const n of layout) { lo = Math.min(lo, n.midi); hi = Math.max(hi, n.midi); }
      for (const f of frames) {
        if (f.f0) { const m = hzToMidi(f.f0); lo = Math.min(lo, m); hi = Math.max(hi, m); }
      }
      if (!isFinite(lo)) { lo = 55; hi = 67; }
      lo = Math.floor(lo) - 2; hi = Math.ceil(hi) + 2;
      if (hi - lo < 6) { const mid = (hi + lo) / 2; lo = mid - 3; hi = mid + 3; }

      const xOf = (t) => (t / maxT) * W;
      const yOf = (m) => H * (1 - (clamp(m, lo, hi) - lo) / (hi - lo));

      // Octave gridlines.
      ctx.strokeStyle = cssVar("--border");
      ctx.lineWidth = 1;
      for (let m = Math.ceil(lo / 12) * 12; m <= hi; m += 12) {
        const y = Math.round(yOf(m)) + 0.5;
        ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(W, y); ctx.stroke();
      }

      // Chosen-note blocks (muted), the selected one highlighted (danger).
      layout.forEach((n) => {
        const x0 = xOf(n.startSec), x1 = xOf(n.endSec), y = yOf(n.midi);
        const isSel = n.seqIndex === selSeq;
        ctx.globalAlpha = isSel ? 1 : 0.5;
        ctx.fillStyle = isSel ? cssVar("--danger") : cssVar("--muted");
        ctx.fillRect(x0, y - 3, Math.max(2, x1 - x0 - 1), 6);
      });
      ctx.globalAlpha = 1;

      // Hummed pitch contour (accent), broken across unvoiced gaps.
      if (frames.length) {
        ctx.strokeStyle = cssVar("--accent");
        ctx.lineWidth = 2;
        ctx.lineJoin = "round";
        ctx.beginPath();
        let pen = false;
        for (const f of frames) {
          if (!f.f0) { pen = false; continue; }
          const x = xOf(f.t), y = yOf(hzToMidi(f.f0));
          if (!pen) { ctx.moveTo(x, y); pen = true; } else ctx.lineTo(x, y);
        }
        ctx.stroke();
      }
    }

    function onStripClick(e) {
      if (!active || !layout.length) return;
      const rect = stripEl.getBoundingClientRect();
      const t = ((e.clientX - rect.left) / rect.width) * maxT;
      let best = layout[0], bestD = Infinity;
      for (const n of layout) {
        if (t >= n.startSec && t <= n.endSec) { best = n; bestD = -1; break; }
        const d = Math.abs((n.startSec + n.endSec) / 2 - t);
        if (bestD >= 0 && d < bestD) { bestD = d; best = n; }
      }
      selectNote(best.seqIndex);
    }

    // ---- rendering + editing ----

    function rerender() {
      if (!tk) return;
      try {
        const r = engrave(tk, seq, opts);
        noteheadMap = r.noteheadMap;
        sheetEl.innerHTML = r.svg;
        wireNoteClicks();
        buildLayout();
        selSeq = snapSel(seq, selSeq);
        applyHighlight();
        updateReadout();
        drawStrip();
      } catch (e) {
        sheetEl.innerHTML = `<p class='hint'>Render error: ${e.message}</p>`;
      }
    }

    function syncEdit() {
      if (refs.onEdit) refs.onEdit(seqToNotes());
    }

    function applyEdit(res) {
      // res = { seq, sel } from an EDITS op. Snapshot the pre-edit state for undo.
      undoStack.push({ seq: cloneSeq(seq), sel: selSeq });
      if (undoStack.length > 200) undoStack.shift();
      redoStack = [];
      seq = res.seq;
      selSeq = res.sel;
      rerender();
      syncEdit();
    }

    function undo() {
      if (!undoStack.length) return;
      redoStack.push({ seq: cloneSeq(seq), sel: selSeq });
      const s = undoStack.pop();
      seq = s.seq; selSeq = s.sel;
      rerender(); syncEdit();
    }

    function redo() {
      if (!redoStack.length) return;
      undoStack.push({ seq: cloneSeq(seq), sel: selSeq });
      const s = redoStack.pop();
      seq = s.seq; selSeq = s.sel;
      rerender(); syncEdit();
    }

    function revert() {
      // Back to the auto draft: notes, key, and chords. Note edits are undoable;
      // this also restores the re-scored key/chords (that part is not undoable).
      undoStack.push({ seq: cloneSeq(seq), sel: selSeq });
      redoStack = [];
      seq = seqFromNotes(original.notes, opts.divisions);
      selSeq = -1;
      opts.key = original.key;
      opts.chords = original.chords;
      rerender();
      syncEdit();
      if (refs.onRescore) {
        refs.onRescore({ key: original.key, key_candidates: original.candidates, chords: original.chords });
      }
      setStatus("Reverted to the auto transcription.");
    }

    // ---- server round-trips (download click / Update chords + key) ----

    function b64Blob(b64, mime) {
      const bin = atob(b64);
      const a = new Uint8Array(bin.length);
      for (let k = 0; k < bin.length; k++) a[k] = bin.charCodeAt(k);
      return new Blob([a], { type: mime });
    }
    function download(blob, name) {
      const a = document.createElement("a");
      a.href = URL.createObjectURL(blob);
      a.download = name;
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(a.href), 1000);
    }
    const exportPayloadNotes = () =>
      seqToNotes().map((n) => ({ midi: n.midi, start_ql: n.start_ql, dur_ql: n.dur_ql }));

    async function doExport(kind) {
      if (!layout.length) { setStatus("Nothing to export yet."); return; }
      setStatus(kind === "midi" ? "Building MIDI..." : "Building MusicXML...");
      try {
        const res = await fetch("/api/export-edited", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            notes: exportPayloadNotes(), tempo: opts.tempo,
            time_sig: opts.timeSig, key: opts.key, chords: opts.chords,
          }),
        });
        if (!res.ok) throw new Error("server " + res.status);
        const data = await res.json();
        if (kind === "midi") download(b64Blob(data.midi_b64, "audio/midi"), "my-hum-edited.mid");
        else download(new Blob([data.musicxml], { type: "application/xml" }), "my-hum-edited.musicxml");
        setStatus("");
      } catch (e) {
        setStatus("Export failed: " + e.message);
      }
    }

    async function doRescore() {
      if (!layout.length) { setStatus("Nothing to score yet."); return; }
      setStatus("Updating chords + key...");
      try {
        const res = await fetch("/api/rescore", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            notes: exportPayloadNotes(), tempo: opts.tempo, time_sig: opts.timeSig,
          }),
        });
        if (!res.ok) throw new Error("server " + res.status);
        const data = await res.json();
        opts.key = data.key;
        opts.chords = data.chords || [];
        rerender();                       // respell + refresh chord symbols on the sheet
        if (refs.onRescore) refs.onRescore(data);
        setStatus(data.key ? "Key: " + data.key : "");
      } catch (e) {
        setStatus("Update failed: " + e.message);
      }
    }

    // ---- input handlers ----

    function onTool(e) {
      const btn = e.target.closest("button[data-op]");
      if (!btn) return;
      const i = selSeq;
      const D = opts.divisions;
      switch (btn.dataset.op) {
        case "pitch-up": applyEdit(EDITS.pitch(seq, i, 1)); break;
        case "pitch-down": applyEdit(EDITS.pitch(seq, i, -1)); break;
        case "oct-up": applyEdit(EDITS.pitch(seq, i, 12)); break;
        case "oct-down": applyEdit(EDITS.pitch(seq, i, -12)); break;
        case "dur-longer": applyEdit(EDITS.duration(seq, i, 1)); break;
        case "dur-shorter": applyEdit(EDITS.duration(seq, i, -1)); break;
        case "split": applyEdit(EDITS.split(seq, i)); break;
        case "merge": applyEdit(EDITS.mergeNext(seq, i)); break;
        case "delete": applyEdit(EDITS.deleteToRest(seq, i)); break;
        case "insert": applyEdit(EDITS.insertAfter(seq, i, D)); break;
        case "undo": undo(); break;
        case "redo": redo(); break;
        case "revert": revert(); break;
        case "rescore": doRescore(); break;
        case "dl-midi": doExport("midi"); break;
        case "dl-xml": doExport("xml"); break;
        default: break;
      }
    }

    function onKey(e) {
      if (!active) return;
      const view = document.getElementById("view-transcriber");
      if (view && view.classList.contains("hidden")) return; // not on this tab
      const t = e.target;
      if (t && /^(INPUT|SELECT|TEXTAREA)$/.test(t.tagName)) return;
      if (e.ctrlKey || e.metaKey) {
        const k = e.key.toLowerCase();
        if (k === "z") { e.preventDefault(); e.shiftKey ? redo() : undo(); }
        else if (k === "y") { e.preventDefault(); redo(); }
        return;
      }
      switch (e.key) {
        case "ArrowRight": e.preventDefault(); nav(1); break;
        case "ArrowLeft": e.preventDefault(); nav(-1); break;
        case "ArrowUp": e.preventDefault(); applyEdit(EDITS.pitch(seq, selSeq, e.shiftKey ? 12 : 1)); break;
        case "ArrowDown": e.preventDefault(); applyEdit(EDITS.pitch(seq, selSeq, e.shiftKey ? -12 : -1)); break;
        case "Delete": case "Backspace": e.preventDefault(); applyEdit(EDITS.deleteToRest(seq, selSeq)); break;
        default: break;
      }
    }

    // ---- lifecycle ----

    async function enter(result) {
      active = true;
      if (result !== originalResult) {
        // New take: reseed everything and discard prior edits/undo history.
        originalResult = result;
        opts = {
          key: result.key,
          timeSig: result.time_sig || [4, 4],
          divisions: result.subdiv || 4,
          tempo: result.tempo_bpm || 120,
          chords: result.chords || [],
        };
        seq = seqFromNotes(result.notes, opts.divisions);
        original = {
          notes: result.notes, key: result.key,
          chords: result.chords || [], candidates: result.key_candidates || [],
        };
        frames = result.frames || [];
        selSeq = -1;
        undoStack = []; redoStack = [];
      }
      // Same take: keep the edited seq, selection, and undo history across the toggle.
      if (paneEl) paneEl.hidden = false;
      setStatus("");
      sheetEl.innerHTML = "<p class='hint'>Loading the editor...</p>";
      try {
        tk = await loadVerovio();
        if (!active) return;              // toggled away while the WASM was loading
        if (selSeq < 0) selSeq = snapSel(seq, 0);
        rerender();
        document.addEventListener("keydown", onKey);
      } catch (e) {
        if (active) sheetEl.innerHTML = `<p class='hint'>Editor failed to load: ${e.message}</p>`;
      }
    }

    function exit() {
      active = false;
      document.removeEventListener("keydown", onKey);
      if (paneEl) paneEl.hidden = true;   // seq/undo kept for a same-take re-entry
    }

    if (stripEl) stripEl.addEventListener("click", onStripClick);
    if (refs.tools) refs.tools.addEventListener("click", onTool);

    return {
      enter, exit,
      isActive: () => active,
      getSeq: () => seq,
      selectedSeqIndex: () => selSeq,
    };
  }

  return {
    parseKey, spell, bestClefSign, notatableSet, decompose, notesToMusicXML,
    seqFromNotes, countNotes, loadVerovio, renderSeq, noteName, createManual,
    EDITS, snapSel, clampMidi,
  };
})();

